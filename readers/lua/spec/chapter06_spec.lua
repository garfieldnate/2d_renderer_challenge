T.test("The spiral", function()
  local c = renders.spiral()
  local ref = read_file("reference/chapter-06/spiral.ppm")
  local p6 = canvas_to_p6(c)
  T.assert_exact(c.width, 320)
  T.assert_exact(c.height, 320)
  local function check(x, y, rr, gg, bb)
    local r, g, b = ppm_pixel(p6, x, y)
    T.assert_eq(r, rr, 1); T.assert_eq(g, gg, 1); T.assert_eq(b, bb, 1)
  end
  check(180, 160, 243, 196, 89)
  check(183, 171, 124, 196, 237)
  check(179, 183, 237, 137, 149)
  check(104, 139, 237, 137, 149)
  check(230, 111, 124, 196, 237)
  check(32, 137, 124, 196, 237)
  check(34, 104, 237, 137, 149)
  check(160, 160, 39, 39, 44)
  check(5, 5, 39, 39, 44)
  check(300, 20, 39, 39, 44)
  T.assert_true(max_channel_difference(p6, ref) <= 1)
end)

