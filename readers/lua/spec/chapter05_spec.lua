-- features/chapter05-*.feature, translated one scenario at a time.
local T = require("helpers")
local tuple_mod = require("tuple")
local path_mod = require("path")
local winding_mod = require("winding")
local shapes_mod = require("shapes")
local coverage_mod = require("coverage")
local ppm_mod = require("ppm")
local renders = require("renders")

local point = tuple_mod.point
local path, move_to, line_to, close, subpaths, edges, bounds, polygon, circle_path =
    path_mod.path, path_mod.move_to, path_mod.line_to, path_mod.close, path_mod.subpaths,
    path_mod.edges, path_mod.bounds, path_mod.polygon, path_mod.circle_path
local crossings, winding_at, inside_nonzero, inside_evenodd, filled =
    winding_mod.crossings, winding_mod.winding_at, winding_mod.inside_nonzero, winding_mod.inside_evenodd, winding_mod.filled
local rasterize, rasterize_within, inside = shapes_mod.rasterize, shapes_mod.rasterize_within, shapes_mod.inside
local ink, coverage_at = coverage_mod.ink, coverage_mod.coverage_at
local canvas_to_p6, ppm_pixel, max_channel_difference, read_file =
    ppm_mod.canvas_to_p6, ppm_mod.ppm_pixel, ppm_mod.max_channel_difference, ppm_mod.read_file

-- ---- chapter05-paths.feature -----------------------------------------------

T.test("An empty path", function()
  local p = path()
  T.assert_exact(#subpaths(p), 0)
  T.assert_exact(#edges(p), 0)
  T.assert_bounds_eq(bounds(p), { 0, 0, 0, 0 })
end)

T.test("A triangle, closed", function()
  local p = path()
  move_to(p, point(1, 1))
  line_to(p, point(9, 1))
  line_to(p, point(5, 8))
  close(p)
  T.assert_exact(#subpaths(p), 1)
  T.assert_true(subpaths(p)[1].closed)
  T.assert_exact(#subpaths(p)[1].points, 3)
  T.assert_tuple_eq(subpaths(p)[1].points[3], point(5, 8))
  T.assert_exact(#edges(p), 3)
  T.assert_tuple_eq(edges(p)[3][1], point(5, 8))
  T.assert_tuple_eq(edges(p)[3][2], point(1, 1))
  T.assert_bounds_eq(bounds(p), { 1, 1, 9, 8 })
end)

T.test("A triangle left open still has three edges", function()
  local p = path()
  move_to(p, point(1, 1))
  line_to(p, point(9, 1))
  line_to(p, point(5, 8))
  T.assert_false(subpaths(p)[1].closed)
  T.assert_exact(#edges(p), 3)
  T.assert_tuple_eq(edges(p)[3][1], point(5, 8))
  T.assert_tuple_eq(edges(p)[3][2], point(1, 1))
end)

T.test("move_to starts a second subpath", function()
  local p = path()
  move_to(p, point(0, 0)); line_to(p, point(10, 0)); line_to(p, point(10, 10)); line_to(p, point(0, 10)); close(p)
  move_to(p, point(3, 3)); line_to(p, point(3, 7)); line_to(p, point(7, 7)); line_to(p, point(7, 3)); close(p)
  T.assert_exact(#subpaths(p), 2)
  T.assert_tuple_eq(subpaths(p)[2].points[1], point(3, 3))
  T.assert_exact(#edges(p), 8)
  T.assert_bounds_eq(bounds(p), { 0, 0, 10, 10 })
end)

T.test("line_to after a close starts a new subpath where the closed one began", function()
  local p = path()
  move_to(p, point(1, 1)); line_to(p, point(4, 1)); line_to(p, point(4, 4)); close(p)
  line_to(p, point(9, 9))
  T.assert_exact(#subpaths(p), 2)
  T.assert_false(subpaths(p)[2].closed)
  T.assert_exact(#subpaths(p)[2].points, 2)
  T.assert_tuple_eq(subpaths(p)[2].points[1], point(1, 1))
  T.assert_tuple_eq(subpaths(p)[2].points[2], point(9, 9))
end)

T.test("line_to with nothing to extend behaves as move_to", function()
  local p = path()
  line_to(p, point(2, 3))
  T.assert_exact(#subpaths(p), 1)
  T.assert_exact(#subpaths(p)[1].points, 1)
  T.assert_tuple_eq(subpaths(p)[1].points[1], point(2, 3))
end)

T.test("A subpath of one point has no edges, and closing nothing does nothing", function()
  local p = path()
  close(p)
  move_to(p, point(1, 1))
  move_to(p, point(2, 2))
  T.assert_exact(#subpaths(p), 2)
  T.assert_exact(#edges(p), 0)
  T.assert_bounds_eq(bounds(p), { 1, 1, 2, 2 })
end)

T.test("A subpath of two points has two edges and encloses nothing", function()
  local p = path()
  move_to(p, point(1, 1))
  line_to(p, point(9, 9))
  T.assert_exact(#edges(p), 2)
  T.assert_exact(winding_at(p, 3, 5), 0)
end)

T.test("polygon is a closed subpath through its points", function()
  local p = polygon(point(0, 0), point(10, 0), point(10, 10), point(0, 10))
  T.assert_exact(#subpaths(p), 1)
  T.assert_true(subpaths(p)[1].closed)
  T.assert_exact(#edges(p), 4)
end)

T.test("circle_path is a polygon standing in for a circle", function()
  local p = circle_path(10, 10, 5, 8)
  T.assert_exact(#subpaths(p)[1].points, 8)
  T.assert_tuple_eq(subpaths(p)[1].points[1], point(15, 10))
  T.assert_tuple_eq(subpaths(p)[1].points[2], point(13.5355, 13.5355))
  T.assert_tuple_eq(subpaths(p)[1].points[3], point(10, 15))
  T.assert_bounds_eq(bounds(p), { 5, 5, 15, 15 })
end)

-- ---- chapter05-winding.feature -----------------------------------------------

T.test("Crossings from inside and outside a square", function()
  local p = polygon(point(0, 0), point(10, 0), point(10, 10), point(0, 10))
  T.assert_exact(crossings(p, 5, 5), 1)
  T.assert_exact(crossings(p, 15, 5), 0)
  T.assert_exact(crossings(p, -1, 5), 2)
end)

T.test("A clockwise square winds once", function()
  local p = polygon(point(0, 0), point(10, 0), point(10, 10), point(0, 10))
  T.assert_exact(winding_at(p, 5, 5), 1)
  T.assert_exact(winding_at(p, 15, 5), 0)
  T.assert_exact(winding_at(p, -1, 5), 0)
  T.assert_exact(winding_at(p, 5, -1), 0)
  T.assert_exact(winding_at(p, 5, 11), 0)
end)

T.test("The same square the other way round winds minus once", function()
  local p = polygon(point(0, 0), point(0, 10), point(10, 10), point(10, 0))
  T.assert_exact(winding_at(p, 5, 5), -1)
  T.assert_exact(crossings(p, 5, 5), 1)
end)

T.test("A ray through a vertex counts it once", function()
  local p = polygon(point(5, 0), point(10, 5), point(5, 10), point(0, 5))
  T.assert_exact(crossings(p, 2, 5), 1)
  T.assert_exact(winding_at(p, 2, 5), 1)
  T.assert_exact(crossings(p, -1, 5), 2)
  T.assert_exact(winding_at(p, -1, 5), 0)
  T.assert_exact(winding_at(p, 12, 5), 0)
  T.assert_exact(winding_at(p, 5, 5), 1)
end)

T.test("The boundary belongs to the top and the left", function()
  local p = polygon(point(0, 0), point(10, 0), point(10, 10), point(0, 10))
  T.assert_exact(winding_at(p, 5, 0), 1)
  T.assert_exact(winding_at(p, 0, 5), 1)
  T.assert_exact(winding_at(p, 0, 0), 1)
  T.assert_exact(winding_at(p, 5, 10), 0)
  T.assert_exact(winding_at(p, 10, 5), 0)
  T.assert_exact(winding_at(p, 10, 10), 0)
end)

T.test("Two rectangles that share an edge cover it once", function()
  local p = path()
  move_to(p, point(0, 0)); line_to(p, point(5, 0)); line_to(p, point(5, 10)); line_to(p, point(0, 10)); close(p)
  move_to(p, point(5, 0)); line_to(p, point(10, 0)); line_to(p, point(10, 10)); line_to(p, point(5, 10)); close(p)
  T.assert_exact(winding_at(p, 2, 5), 1)
  T.assert_exact(winding_at(p, 5, 5), 1)
  T.assert_exact(winding_at(p, 8, 5), 1)
end)

T.test("A diamond wound twice has winding number 2", function()
  local p = path()
  move_to(p, point(5, 0)); line_to(p, point(10, 5)); line_to(p, point(5, 10)); line_to(p, point(0, 5))
  line_to(p, point(5, 0)); line_to(p, point(10, 5)); line_to(p, point(5, 10)); line_to(p, point(0, 5))
  close(p)
  T.assert_exact(#edges(p), 8)
  T.assert_exact(winding_at(p, 5, 5), 2)
  T.assert_exact(crossings(p, 5, 5), 2)
  T.assert_exact(winding_at(p, 12, 5), 0)
end)

T.test("The polygon circle", function()
  local p = circle_path(10, 10, 5, 8)
