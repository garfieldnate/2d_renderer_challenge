T.test("The star by the center question", function()
  local c = renders.star_centers()
  local ref = read_file("reference/chapter-05/star-centers.ppm")
  local p6 = canvas_to_p6(c)
  T.assert_exact(c.width, 320)
  T.assert_exact(c.height, 160)
  local function check(x, y, rr, gg, bb)
    local r, g, b = ppm_pixel(p6, x, y)
    T.assert_eq(r, rr, 1); T.assert_eq(g, gg, 1); T.assert_eq(b, bb, 1)
  end
  check(80, 80, 243, 196, 89)
  check(240, 80, 39, 39, 44)
  check(80, 20, 243, 196, 89)
  check(240, 20, 243, 196, 89)
  check(30, 60, 243, 196, 89)
  check(190, 60, 243, 196, 89)
  check(80, 120, 39, 39, 44)
  check(80, 10, 39, 39, 44)
  check(10, 10, 39, 39, 44)
  T.assert_true(max_channel_difference(p6, ref) <= 1)
end)

