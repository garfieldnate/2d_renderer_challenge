-- ---- chapter05-rules.feature -----------------------------------------------

T.test("A single loop is inside under both rules", function()
  local p = polygon(point(0, 0), point(10, 0), point(10, 10), point(0, 10))
  T.assert_true(inside_nonzero(p, 5, 5))
  T.assert_true(inside_evenodd(p, 5, 5))
  T.assert_false(inside_nonzero(p, 15, 5))
  T.assert_false(inside_evenodd(p, 15, 5))
end)

T.test("An inner loop the other way round is a hole under both rules", function()
  local p = path()
  move_to(p, point(0, 0)); line_to(p, point(10, 0)); line_to(p, point(10, 10)); line_to(p, point(0, 10)); close(p)
  move_to(p, point(3, 3)); line_to(p, point(3, 7)); line_to(p, point(7, 7)); line_to(p, point(7, 3)); close(p)
  T.assert_exact(winding_at(p, 5, 5), 0)
  T.assert_exact(winding_at(p, 1, 1), 1)
  T.assert_false(inside_nonzero(p, 5, 5))
  T.assert_false(inside_evenodd(p, 5, 5))
  T.assert_true(inside_nonzero(p, 1, 1))
end)

T.test("An inner loop the same way round is a hole only under even-odd", function()
  local p = path()
  move_to(p, point(0, 0)); line_to(p, point(10, 0)); line_to(p, point(10, 10)); line_to(p, point(0, 10)); close(p)
  move_to(p, point(3, 3)); line_to(p, point(7, 3)); line_to(p, point(7, 7)); line_to(p, point(3, 7)); close(p)
  T.assert_exact(winding_at(p, 5, 5), 2)
  T.assert_true(inside_nonzero(p, 5, 5))
  T.assert_false(inside_evenodd(p, 5, 5))
end)

T.test("A loop wound twice vanishes under even-odd", function()
  local p = path()
  move_to(p, point(5, 0)); line_to(p, point(10, 5)); line_to(p, point(5, 10)); line_to(p, point(0, 5))
  line_to(p, point(5, 0)); line_to(p, point(10, 5)); line_to(p, point(5, 10)); line_to(p, point(0, 5))
  close(p)
  T.assert_true(inside_nonzero(p, 5, 5))
  T.assert_false(inside_evenodd(p, 5, 5))
end)

T.test("The pentagram's center is inside under nonzero and outside under even-odd", function()
  local p = renders.star()
  T.assert_true(inside_nonzero(p, 80.5, 80.5))
  T.assert_false(inside_evenodd(p, 80.5, 80.5))
  T.assert_true(inside_nonzero(p, 80.5, 20))
  T.assert_true(inside_evenodd(p, 80.5, 20))
  T.assert_false(inside_nonzero(p, 80.5, 120))
  T.assert_false(inside_evenodd(p, 80.5, 120))
end)

T.test("A filled path is a shape", function()
  local s = filled(polygon(point(2, 2), point(6, 2), point(6, 6), point(2, 6)), "nonzero")
  local cov = rasterize(s, 8, 8)
  T.assert_true(inside(s, 3, 3))
  T.assert_false(inside(s, 7, 3))
  T.assert_eq(coverage_at(cov, 3, 3), 1)
  T.assert_eq(coverage_at(cov, 1, 3), 0)
  T.assert_eq(coverage_at(cov, 6, 3), 0)
  T.assert_eq(ink(cov), 16)
end)

T.test("A filled path takes the rule seriously", function()
  local p = renders.star()
  local a = filled(p, "nonzero")
  local b = filled(p, "evenodd")
  local ca = rasterize(a, 160, 160)
  local cb = rasterize(b, 160, 160)
  T.assert_eq(coverage_at(ca, 80, 80), 1)
  T.assert_eq(coverage_at(cb, 80, 80), 0)
  T.assert_eq(coverage_at(ca, 80, 20), 1)
  T.assert_eq(coverage_at(cb, 80, 20), 1)
  T.assert_eq(coverage_at(ca, 80, 10), 0.0625)
  T.assert_eq(coverage_at(cb, 80, 10), 0.0625)
  T.assert_eq(ink(ca), 5499.9375)
  T.assert_eq(ink(cb), 3800.375)
end)

T.test("Rasterizing within the bounds gives the same coverage", function()
  local p = renders.star()
  local s = filled(p, "evenodd")
  local full = rasterize(s, 160, 160)
  local within = rasterize_within(s, bounds(p), 160, 160)
  T.assert_eq(ink(within), ink(full))
  T.assert_eq(coverage_at(within, 80, 20), coverage_at(full, 80, 20))
  T.assert_eq(coverage_at(within, 13, 58), coverage_at(full, 13, 58))
  T.assert_eq(coverage_at(within, 10, 10), 0)
end)

T.test("The box is inclusive of the pixels it touches, and clipped to the buffer", function()
  local s = filled(polygon(point(1.5, 1.5), point(6.5, 1.5), point(6.5, 6.5), point(1.5, 6.5)), "nonzero")
  local cov = rasterize_within(s, { minx = 1.5, miny = 1.5, maxx = 6.5, maxy = 6.5 }, 8, 8)
  local big = rasterize_within(s, { minx = -5, miny = -5, maxx = 20, maxy = 20 }, 8, 8)
  T.assert_eq(coverage_at(cov, 1, 1), 0.25)
  T.assert_eq(coverage_at(cov, 6, 6), 0.25)
  T.assert_eq(coverage_at(cov, 3, 3), 1)
  T.assert_eq(ink(cov), 25)
  T.assert_eq(ink(big), 25)
end)

