-- helper: build a matrix from a Gherkin data table given row by row
local function table_matrix(rows)
  local vals = {}
  for _, row in ipairs(rows) do
    for _, v in ipairs(row) do vals[#vals + 1] = v end
  end
  return matrix3(table.unpack(vals))
end

-- ---- chapter04-tuples.feature -----------------------------------------------

T.test("A point has w = 1", function()
  local p = point(4, -4)
  T.assert_eq(p.x, 4); T.assert_eq(p.y, -4); T.assert_eq(p.w, 1)
end)

T.test("A vector has w = 0", function()
  local v = vector(4, -4)
  T.assert_eq(v.x, 4); T.assert_eq(v.y, -4); T.assert_eq(v.w, 0)
end)

T.test("The difference of two points is the vector between them", function()
  local a, b = point(3, 2), point(5, 6)
  T.assert_tuple_eq(b - a, vector(2, 4))
  T.assert_tuple_eq(a - b, vector(-2, -4))
end)

T.test("A point plus a vector is a point", function()
  local p, v = point(3, -2), vector(-2, 3)
  T.assert_tuple_eq(p + v, point(1, 1))
  T.assert_tuple_eq(p - v, point(5, -5))
end)

T.test("A vector plus a vector is a vector", function()
  local a, b = vector(3, -2), vector(-2, 3)
  T.assert_tuple_eq(a + b, vector(1, 1))
  T.assert_tuple_eq(a - b, vector(5, -5))
end)

T.test("Negating, scaling and dividing a vector", function()
  local v = vector(1, -2)
  T.assert_tuple_eq(-v, vector(-1, 2))
  T.assert_tuple_eq(v * 3.5, vector(3.5, -7))
  T.assert_tuple_eq(v * 0.5, vector(0.5, -1))
  T.assert_tuple_eq(v / 2, vector(0.5, -1))
end)

T.test("The magnitude of a vector", function()
  T.assert_eq(magnitude(vector(1, 0)), 1)
  T.assert_eq(magnitude(vector(0, 1)), 1)
  T.assert_eq(magnitude(vector(3, 4)), 5)
  T.assert_eq(magnitude(vector(-3, -4)), 5)
  T.assert_eq(magnitude(vector(-1, -2)), 2.2361)
end)

T.test("Normalizing a vector", function()
  T.assert_tuple_eq(normalize(vector(4, 0)), vector(1, 0))
  T.assert_tuple_eq(normalize(vector(1, 2)), vector(0.4472, 0.8944))
  T.assert_eq(magnitude(normalize(vector(1, 2))), 1)
