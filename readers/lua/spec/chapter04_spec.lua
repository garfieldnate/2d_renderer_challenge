T.test("The cross product of two vectors is a number", function()
  local a, b = vector(1, 0), vector(0, 1)
  T.assert_eq(cross(a, b), 1)
  T.assert_eq(cross(b, a), -1)
  T.assert_eq(cross(a, a), 0)
