T.test("Constructing and inspecting a matrix", function()
  local M = table_matrix({ { 1, 2, 3 }, { 4, 5, 6 }, { 7, 8, 9 } })
  T.assert_eq(mat_get(M, 0, 0), 1)
  T.assert_eq(mat_get(M, 0, 2), 3)
  T.assert_eq(mat_get(M, 1, 0), 4)
  T.assert_eq(mat_get(M, 1, 1), 5)
  T.assert_eq(mat_get(M, 2, 0), 7)
  T.assert_eq(mat_get(M, 2, 2), 9)
  T.assert_mat_eq(M, matrix3(1, 2, 3, 4, 5, 6, 7, 8, 9))
end)

T.test("Matrix equality with identical matrices", function()
  local A = matrix3(1, 2, 3, 4, 5, 6, 7, 8, 9)
  local B = matrix3(1, 2, 3, 4, 5, 6, 7, 8, 9)
  T.assert_mat_eq(A, B)
end)

T.test("Matrix equality with different matrices", function()
  local A = matrix3(1, 2, 3, 4, 5, 6, 7, 8, 9)
  local B = matrix3(1, 2, 3, 4, 5, 6, 7, 8, 8)
  T.assert_false(T.mat_eq(A, B))
end)

T.test("Multiplying two matrices", function()
  local A = table_matrix({ { 1, 2, 3 }, { 4, 5, 6 }, { 7, 8, 9 } })
  local B = table_matrix({ { 2, -1, 0 }, { 1, 3, 1 }, { 0, 1, 2 } })
  local expected = table_matrix({ { 4, 8, 8 }, { 13, 17, 17 }, { 22, 26, 26 } })
  T.assert_mat_eq(A * B, expected)
end)

T.test("Matrix multiplication is not commutative", function()
  local A = matrix3(1, 2, 3, 4, 5, 6, 7, 8, 9)
  local B = matrix3(2, -1, 0, 1, 3, 1, 0, 1, 2)
  T.assert_false(T.mat_eq(A * B, B * A))
end)

T.test("A matrix multiplied by a point", function()
  local A = table_matrix({ { 1, 2, 3 }, { 4, 5, 6 }, { 0, 0, 1 } })
  local p = point(1, 2)
  T.assert_tuple_eq(A * p, point(8, 20))
end)

T.test("A matrix multiplied by a vector ignores the last column", function()
  local A = table_matrix({ { 1, 2, 3 }, { 4, 5, 6 }, { 0, 0, 1 } })
  local v = vector(1, 2)
  T.assert_tuple_eq(A * v, vector(5, 14))
end)

T.test("Multiplying by the identity matrix changes nothing", function()
  local A = matrix3(0, 1, 2, 1, 2, 4, 2, 4, 8)
  local p = point(1, 2)
  T.assert_mat_eq(A * identity(), A)
  T.assert_mat_eq(identity() * A, A)
  T.assert_tuple_eq(identity() * p, p)
end)

T.test("Transposing a matrix", function()
  local A = table_matrix({ { 0, 9, 3 }, { 9, 8, 0 }, { 1, 8, 5 } })
  local expected = table_matrix({ { 0, 9, 1 }, { 9, 8, 8 }, { 3, 0, 5 } })
  T.assert_mat_eq(transpose(A), expected)
end)

T.test("Transposing the identity matrix", function()
  T.assert_mat_eq(transpose(identity()), identity())
end)

T.test("The determinant of a 3 by 3 matrix", function()
  local A = table_matrix({ { 1, 2, 6 }, { -5, 8, -4 }, { 2, 6, 4 } })
  T.assert_eq(determinant(A), -196)
end)

T.test("The determinant of a transform is the area factor", function()
  T.assert_eq(determinant(identity()), 1)
  T.assert_eq(determinant(scaling(2, 3)), 6)
  T.assert_eq(determinant(rotation(0.7)), 1)
  T.assert_eq(determinant(translation(4, 9)), 1)
  T.assert_eq(determinant(scaling(-1, 1)), -1)
end)

T.test("Testing an invertible matrix for invertibility", function()
  local A = table_matrix({ { 3, 0, 2 }, { 2, 0, -2 }, { 0, 1, 1 } })
  T.assert_eq(determinant(A), 10)
  T.assert_true(is_invertible(A))
end)

T.test("Testing a non-invertible matrix for invertibility", function()
  local A = table_matrix({ { 1, 2, 3 }, { 2, 4, 6 }, { 0, 0, 1 } })
  T.assert_eq(determinant(A), 0)
  T.assert_false(is_invertible(A))
end)

T.test("Invertibility is an exact test against zero", function()
  T.assert_true(is_invertible(scaling(0.0001, 1)))
  T.assert_exact(determinant(scaling(0.0001, 1)), 0.0001)
  T.assert_tuple_eq(inverse(scaling(0.0001, 1)) * point(0.0001, 3), point(1, 3))
end)

T.test("Calculating the inverse of a matrix", function()
  local A = table_matrix({ { 3, 0, 2 }, { 2, 0, -2 }, { 0, 1, 1 } })
  local B = inverse(A)
  T.assert_eq(mat_get(B, 0, 0), 0.2)
  T.assert_eq(mat_get(B, 1, 2), 1)
  T.assert_eq(mat_get(B, 2, 1), -0.3)
  local expected = table_matrix({ { 0.2, 0.2, 0 }, { -0.2, 0.3, 1 }, { 0.2, -0.3, 0 } })
  T.assert_mat_eq(B, expected)
  T.assert_mat_eq(A * B, identity())
end)

T.test("Multiplying a product by its inverse", function()
  local A = matrix3(1, 2, 3, 4, 5, 6, 7, 8, 9)
  local B = matrix3(2, -1, 0, 1, 3, 1, 0, 1, 2)
  local C = A * B
  T.assert_mat_eq(C * inverse(B), A)
end)

T.test("The inverse of a transform is a transform", function()
  local A = translation(5, -3) * rotation(PI / 6) * scaling(2, 3)
  local B = inverse(A)
  T.assert_eq(mat_get(B, 2, 0), 0)
  T.assert_eq(mat_get(B, 2, 1), 0)
  T.assert_eq(mat_get(B, 2, 2), 1)
  T.assert_eq(mat_get(B, 0, 0), 0.4330)
  T.assert_eq(mat_get(B, 0, 2), -1.4151)
  T.assert_eq(mat_get(B, 1, 2), 1.6994)
  T.assert_mat_eq(B * A, identity())
end)

-- ---- chapter04-transforms.feature -----------------------------------------------

T.test("Multiplying by a translation matrix", function()
  local t, p = translation(5, -3), point(-3, 4)
  T.assert_tuple_eq(t * p, point(2, 1))
end)

T.test("The inverse of a translation moves the other way", function()
  local t, p = translation(5, -3), point(-3, 4)
  T.assert_tuple_eq(inverse(t) * p, point(-8, 7))
end)

T.test("Translation does not affect vectors", function()
  local t, v = translation(5, -3), vector(-3, 4)
  T.assert_tuple_eq(t * v, v)
end)

T.test("A scaling matrix applied to a point", function()
  local s, p = scaling(2, 3), point(-4, 6)
  T.assert_tuple_eq(s * p, point(-8, 18))
end)

T.test("A scaling matrix applied to a vector", function()
  local s, v = scaling(2, 3), vector(-4, 6)
  T.assert_tuple_eq(s * v, vector(-8, 18))
end)

T.test("The inverse of a scaling shrinks", function()
  local s, v = scaling(2, 3), vector(-4, 6)
  T.assert_tuple_eq(inverse(s) * v, vector(-2, 2))
end)

T.test("Reflection is scaling by a negative value", function()
  local s, p = scaling(-1, 1), point(2, 3)
  T.assert_tuple_eq(s * p, point(-2, 3))
end)

T.test("A positive rotation turns x toward y", function()
  local p = point(1, 0)
  T.assert_tuple_eq(rotation(PI / 4) * p, point(0.7071, 0.7071))
  T.assert_tuple_eq(rotation(PI / 2) * p, point(0, 1))
  T.assert_tuple_eq(rotation(PI) * p, point(-1, 0))
end)

T.test("The inverse of a rotation turns the other way", function()
  local p = point(1, 0)
  T.assert_tuple_eq(inverse(rotation(PI / 4)) * p, point(0.7071, -0.7071))
  T.assert_tuple_eq(rotation(-PI / 4) * p, point(0.7071, -0.7071))
end)

T.test("A rotation preserves length", function()
  local v = vector(3, 4)
  T.assert_eq(magnitude(rotation(1.2) * v), 5)
  T.assert_eq(magnitude(rotation(-2.8) * v), 5)
end)

T.test("Shearing moves x in proportion to y", function()
  local s, p = shearing(1, 0), point(2, 3)
  T.assert_tuple_eq(s * p, point(5, 3))
end)

T.test("Shearing moves y in proportion to x", function()
  local s, p = shearing(0, 1), point(2, 3)
  T.assert_tuple_eq(s * p, point(2, 5))
end)

T.test("Individual transformations are applied in sequence", function()
  local p = point(1, 0)
  local A, B, C = rotation(PI / 2), scaling(5, 5), translation(10, 5)
  local p2 = A * p
  local p3 = B * p2
  local p4 = C * p3
  T.assert_tuple_eq(p2, point(0, 1))
  T.assert_tuple_eq(p3, point(0, 5))
  T.assert_tuple_eq(p4, point(10, 10))
end)

T.test("Chained transformations must be applied in reverse order", function()
  local p = point(1, 0)
  local A, B, C = rotation(PI / 2), scaling(5, 5), translation(10, 5)
  local Tm = C * B * A
  T.assert_tuple_eq(Tm * p, point(10, 10))
end)

T.test("The other order is a different transform", function()
  local p = point(1, 0)
  local A, B, C = rotation(PI / 2), scaling(5, 5), translation(10, 5)
  local Tm = A * B * C
  T.assert_tuple_eq(Tm * p, point(-25, 55))
end)

T.test("Rotating about a point that isn't the origin", function()
  local Tm = translation(4, 4) * rotation(PI / 2) * translation(-4, -4)
  T.assert_tuple_eq(Tm * point(6, 4), point(4, 6))
  T.assert_tuple_eq(Tm * point(4, 4), point(4, 4))
end)

-- ---- chapter04-scale.feature -----------------------------------------------

T.test("The identity, a translation and a rotation don't stretch", function()
  T.assert_eq(approx_scale(identity()), 1)
  T.assert_eq(approx_scale(translation(7, 9)), 1)
  T.assert_eq(approx_scale(rotation(1.1)), 1)
end)

T.test("A uniform scale is reported exactly", function()
  T.assert_eq(approx_scale(scaling(2, 2)), 2)
  T.assert_eq(approx_scale(scaling(0.5, 0.5)), 0.5)
  T.assert_eq(approx_scale(scaling(3, 3) * rotation(0.7)), 3)
  T.assert_eq(approx_scale(translation(5, 5) * scaling(3, 3)), 3)
end)

T.test("A reflection is not a negative scale", function()
  T.assert_eq(approx_scale(scaling(-2, 2)), 2)
end)

T.test("A non-uniform scale is reported as the geometric mean", function()
  T.assert_eq(approx_scale(scaling(4, 1)), 2)
  T.assert_eq(approx_scale(scaling(4, 1) * rotation(0.4)), 2)
  T.assert_eq(approx_scale(scaling(9, 1)), 3)
end)

T.test("A shear that preserves area reports 1", function()
  T.assert_eq(approx_scale(shearing(1, 0)), 1)
  T.assert_eq(approx_scale(shearing(0.5, 0.5)), 0.8660)
end)

T.test("A collapsed transform reports 0", function()
  T.assert_eq(approx_scale(scaling(0, 1)), 0)
  T.assert_eq(approx_scale(matrix3(1, 2, 0, 2, 4, 0, 0, 0, 1)), 0)
end)

